// Builds the mockup screens: node build.mjs (from this folder, or any other).
// Each screen is one self-contained HTML file: the styles, the script and the brand
// fonts are inside it, so a file opens on its own from a phone, a preview or a disk.
import { readFileSync, writeFileSync } from "node:fs";
import { index } from "./src/index.mjs";
import { screens } from "./src/screens.mjs";
import { shell } from "./src/shell.mjs";

const here = (p) => new URL(p, import.meta.url);
const read = (p) => readFileSync(here(p), "utf8");
const brand = JSON.parse(read("../../server/brand/tokens.json"));

const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const colors = (palette) =>
  Object.entries(palette)
    .filter(([k]) => !k.startsWith("map"))
    .map(([k, v]) => `--c-${kebab(k)}:${v};`)
    .join("");
const stack = (name, fallback) => `"${name}", ${fallback}`;
const tokens = `
:root{color-scheme:light dark;${colors(brand.color)}
--f-body:${stack(brand.font.body, "system-ui, sans-serif")};
--f-heading:${stack(brand.font.heading, "system-ui, sans-serif")};
--f-mono:${stack(brand.font.mono, "ui-monospace, monospace")};
--r-sm:${brand.radius.sm}px;--r-md:${brand.radius.md}px;--r-lg:${brand.radius.lg}px;}
@media (prefers-color-scheme: dark){:root:not([data-theme="light"]){${colors(brand.colorDark)}}}
:root[data-theme="light"]{color-scheme:light;}
:root[data-theme="dark"]{color-scheme:dark;${colors(brand.colorDark)}}`;

const FONTS = [
  [brand.font.heading, 800, "bricolage-grotesque-latin-800-normal"],
  [brand.font.body, 400, "instrument-sans-latin-400-normal"],
  [brand.font.body, 600, "instrument-sans-latin-600-normal"],
  [brand.font.mono, 500, "dm-mono-latin-500-normal"],
];
const fonts = FONTS.map(([family, weight, file]) => {
  const data = readFileSync(here(`../../server/brand/fonts/${file}.woff2`));
  return `@font-face{font-family:"${family}";font-weight:${weight};font-display:swap;src:url(data:font/woff2;base64,${data.toString("base64")}) format("woff2");}`;
}).join("\n");

const css = read("src/kit.css");
const js = read("src/kit.js");

function page({ title, states = [["default", "Default"]], plain, body }) {
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<title>${title} · Kilolane admin (mockup)</title>
<!-- Generated by build.mjs from src/. Do not edit by hand. A design mockup with invented
     sample data: no part of it is connected to a server. -->
<style>${fonts}
${tokens}
${css}</style>
</head>
<body data-states="${states.map(([id]) => id).join(" ")}"${plain ? ' class="plain"' : ""}>
${body}
<script>${js}</script>
</body>
</html>
`;
}

for (const s of screens)
  writeFileSync(
    here(`${s.file}.html`),
    page({ ...s, body: shell({ ...s, states: s.states }) }),
  );
writeFileSync(here("index.html"), page(index(screens)));
console.log(`built ${screens.length + 1} files`);
