const ALPHA2 = new Map(
  CODES.trim()
    .split(/\s+/)
    .map((pair) => [pair.slice(0, 3), pair.slice(3)]),
);

/**
 * The country's name in `locale`, for example "Germany" or "Deutschland" for "DEU".
 * The code itself when it is unknown, or where the device has no `Intl.DisplayNames`.
 */
export function countryName(code: string, locale: string): string {
  const region = ALPHA2.get(code.toUpperCase());
  if (!region) return code;
  try {
    const names = new Intl.DisplayNames([locale, "en"], {
      type: "region",
      fallback: "none",
    });
    return names.of(region) ?? code;
  } catch {
    return code;
  }
}
