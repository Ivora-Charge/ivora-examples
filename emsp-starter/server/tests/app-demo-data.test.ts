import { describe, expect, it } from "vitest";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { DEMO_PEER_ID, demoLocationStore } from "@/lib/locations/registry";
import {
  locationDetail,
  parseLocationAppId,
  searchLocations,
  tariffsFor,
  tariffsOfLocation,
} from "@/lib/locations/search";

/**
 * The driver app's offline demo shows the mock CPO's sample locations exactly as this
 * server's location API would: `app/src/demo/locations.json`. This test fails when the
 * two drift apart. After changing the sample data or the API's shape, run
 * `npm run app:demo-data` to write the file again.
 */
const FILE = join(__dirname, "../../app/src/demo/locations.json");
// A fixed time, so time-limited tariffs pick the same price on every run.
const AT = new Date("2026-10-01T10:00:00Z");

async function snapshot() {
  const store = demoLocationStore();
  const { items } = await searchLocations(
    store,
    [DEMO_PEER_ID],
    { limit: 100, offset: 0 },
    AT,
  );
  const locations = [];
  for (const item of items) {
    const held = await store.getLocation(parseLocationAppId(item.id)!);
    const byPeer = await tariffsFor(store, [held!]);
    locations.push(locationDetail(held!, tariffsOfLocation(held!, byPeer), AT));
  }
  return {
    $comment: "Generated by server/tests/app-demo-data.test.ts",
    locations,
  };
}

describe("the app's offline demo data", () => {
  it("is the mock CPO's locations as the API shows them (npm run app:demo-data)", async () => {
    const json = `${JSON.stringify(await snapshot(), null, 2)}\n`;
    if (process.env.UPDATE_APP_DEMO === "1") writeFileSync(FILE, json);
    expect(readFileSync(FILE, "utf8")).toBe(json);
  });
});
